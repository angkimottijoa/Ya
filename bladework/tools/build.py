rgb = lambda h: tuple(int(h[i:i + 2], 16) for i in (1, 3, 5)) + (255,)

def sprite(kind, tier):
    L, B, D, O, A, AD = (rgb(c) for c in TIERS[tier])
    W1, W2, W3, WO = (rgb(c) for c in WOOD)
    px = {}
    def put(u, v, c):
        if (u + v) % 2: return
        x, yy = (u + v) // 2, (u - v) // 2
        if 0 <= x < 16 and 0 <= yy < 16: px[(x, 15 - yy)] = c
    def band(u0, u1, half, colf, center=lambda u: 0):
        for u in range(u0, u1 + 1):
            h = half(u) if callable(half) else half
            for v in range(-h, h + 1):
                put(u, v + center(u), colf(u, v))
    blade = lambda u, v: L if v < 0 else (B if v == 0 else D)
    wood = lambda u, v: W1 if v < 0 else (W2 if v == 0 else W3)
    wrap = lambda u, v: (W3 if (u // 2) % 2 else A) if v <= 0 else AD
    acc = lambda u, v: A if v <= 0 else AD
    if kind == "dagger":
        band(5, 10, 1, wood); band(4, 5, 1, acc); band(11, 12, 3, acc)
        band(13, 23, lambda u: min(2, (24 - u) // 2), blade)
    elif kind == "longsword":
        band(2, 9, 1, wrap); band(1, 2, 1, acc); band(10, 11, 4, acc)
        band(12, 30, lambda u: min(1, 30 - u), blade)
        band(12, 26, 0, lambda u, v: D)
    elif kind == "greatsword":
        band(2, 7, 1, wood); band(0, 2, 2, acc); band(8, 9, 5, acc)
        band(10, 30, lambda u: min(3, 30 - u), blade)
        band(11, 25, 0, lambda u, v: D)
    elif kind == "spear":
        band(1, 21, 1, wood); band(20, 22, 2, acc)
        band(23, 30, lambda u: max(0, min(3, u - 22, 30 - u)), blade)
    elif kind == "saber":
        curve = lambda u: -round(((u - 11) ** 2) / 55) if u > 11 else 0
        band(2, 9, 1, wrap); band(1, 2, 1, acc); band(10, 11, 2, acc)
        band(12, 29, lambda u: 1 if u < 28 else 0,
             lambda u, v: L if v < 0 else (B if v == 0 else D), curve)
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for (x, y), c in px.items(): img.putpixel((x, y), c)
    for x in range(16):               # outline pass
        for y in range(16):
            if (x, y) in px: continue
            near = [px.get((x + dx, y + dy)) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))]
            if any(near):
                woodish = all(n in (None, W1, W2, W3) for n in near)
                img.putpixel((x, y), WO if woodish else O)
    return img

