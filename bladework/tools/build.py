def codex():
    pal = {"o": "#2a1210", "r": "#b5382e", "R": "#8f241f", "D": "#5e1513",
           "g": "#f2d24b", "w": "#f1ead2", "W": "#c9bf9d"}
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(CODEX.strip().splitlines()):
        for x, ch in enumerate(row):
            if ch in pal: img.putpixel((x, y), rgb(pal[ch]))
    return img

