def pack_icon(path, flip):
    S = 256; img = Image.new("RGBA", (S, S))
    for y in range(S):
        for x in range(S):
            d = math.hypot(x - S / 2, y - S / 2) / (S * 0.75)
            img.putpixel((x, y), (int(46 - 30 * d), int(20 - 12 * d), int(34 - 14 * d), 255))
    a = sprites["netherite_greatsword"].resize((208, 208), Image.NEAREST)
    b = sprites["diamond_saber"].resize((208, 208), Image.NEAREST).transpose(Image.FLIP_LEFT_RIGHT)
    for s in ((b, a) if flip else (a, b)): img.alpha_composite(s, (24, 24))
    img.save(path)
